a = 12
b = 5

#bitWise OR (|)
c = a | b
print('\n', 20*'=', '\n')
print('nilai',a,'Binary:', format(a, '08b'))
print('nilai',b,'Binary:', format(b, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))


#bitWise AND (&)
c = a & b
print('\n', 20*'=', '\n')
print('nilai',a,'Binary:', format(a, '08b'))
print('nilai',b,'Binary:', format(b, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))

#bitWise XOR (^)
c = a ^ b
print('\n', 20*'=', '\n')
print('nilai',a,'Binary:', format(a, '08b'))
print('nilai',b,'Binary:', format(b, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))
print('\n', 20*'=', '\n')

#bitWise NOT (~)
c = ~a
print('nilai',a,'Binary:', format(a, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))

#shifting RIGHT
c = a >> 2
print('nilai',a,'Binary:', format(a, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))
print('\n', 20*'=', '\n')

#shifting lEFT
c = a << 2
print('nilai',a,'Binary:', format(a, '08b'))
print('\n', 20*'-', '\n')
print('nilai',c,'Binary:', format(c, '08b'))
print('\n', 20*'=', '\n')

